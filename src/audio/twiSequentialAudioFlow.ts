export const CANONICAL_IVR_CATEGORIES: IvrCategoryDefinition[] = CANONICAL_IVR_CATEGORY_DEFINITIONS.map((category) => ({
  ...category,
  prompts: category.prompts.map((prompt) => {
    if (isDynamicPrompt(prompt.promptId)) {
      return {
        ...prompt,
        audioUrl: `/api/audio/prompt-tts/twi/${prompt.promptId}`,
        fallbackAudioUrl: undefined,
      };
    }

    const recording = getRecordingByPromptId(prompt.promptId, "twi");
    return {
      ...prompt,
      audioUrl: recording?.url || "",
      fallbackAudioUrl: undefined,
    };
  }),
}));

export function getFlowStepById(stepId: string): FlowStepDefinition | undefined {
  return TWI_SEQUENTIAL_FLOW_STEPS.find((s) => s.id === stepId);
}

export function getFlowStepByIndex(index: number): FlowStepDefinition | undefined {
  return TWI_SEQUENTIAL_FLOW_STEPS.find((s) => s.stepIndex === index);
}

export function getNextFlowStep(
  currentStepId: string,
  satisfiedCondition?: FlowAdvanceCondition
): FlowStepDefinition | undefined {
  const current = getFlowStepById(currentStepId);
  if (!current?.nextStepId || (current.advanceCondition && current.advanceCondition !== satisfiedCondition)) {
    return undefined;
  }
  return getFlowStepById(current.nextStepId);
}

export function getAllIvrCategories(): IvrCategoryDefinition[] {
  return CANONICAL_IVR_CATEGORIES;
}

export function getIvrCategoryById(id: string): IvrCategoryDefinition | undefined {
  return CANONICAL_IVR_CATEGORIES.find((c) => c.id === id);
}

export function getIvrCategoryByNumber(num: number): IvrCategoryDefinition | undefined {
  return CANONICAL_IVR_CATEGORIES.find((c) => c.categoryNumber === num);
}

export function getAllCanonicalPrompts(): IvrPromptItem[] {
  return CANONICAL_IVR_CATEGORIES.flatMap((c) => c.prompts);
}

export function getCanonicalPromptById(promptId: string): IvrPromptItem | undefined {
  for (const cat of CANONICAL_IVR_CATEGORIES) {
    const found = cat.prompts.find((p) => p.promptId === promptId);
    if (found) return found;
  }
  return undefined;
}

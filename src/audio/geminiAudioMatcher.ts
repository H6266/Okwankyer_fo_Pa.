/**
 * Ɔkwankyerɛfo Pa - AI-Driven Audio Link Matcher & Literacy Engine (geminiAudioMatcher.ts)
 * 
 * Optimization Highlights:
 * 1. In-Memory Cache: Results cached by normalized text + language. Static prompts hit cache with 0 tokens (< 1ms).
 * 2. Local-First Matching: matchReplyToAudio & dynamic regex check first. Exact/high-confidence matches skip Gemini entirely.
 * 3. Gemini Audio Matching Gated: Gemini is ONLY called when the reply originated from the Gemini conversation flow,
 *    retrieving the reply stored in memory and evaluating against the prompt catalog manifest.
 * 4. Resilient Fallback: If Gemini is rate-limited or offline, semanticCatalogFallback ensures zero downtime.
 */

import { AUDIO_RECORDINGS } from "./recordingRegistry";
import { TWI_SEQUENTIAL_FLOW_STEPS } from "./twiSequentialAudioFlow";
import { UnifiedGeminiClient } from "../services/geminiClient";
import promptManifest from "../../Audio_files/prompts.json";
import { matchReplyToAudio } from "./replyAudioMatcher";

export interface GeminiAudioMatchResult {
  matchFound: boolean;
  promptId?: string;
  audioUrl?: string;
  title?: string;
  spokenText?: string;
  reason: string;
  requiresTts: boolean;
  literacyContext?: string;
  confidence?: number;
}

export interface CallerLiteracyOptions {
  literacyLevel?: "low" | "standard" | "elderly";
  prefersColloquial?: boolean;
  sessionId?: string;
  isGeminiConversation?: boolean;
}

export interface StoredGeminiReply {
  text: string;
  language: string;
  sessionId?: string;
  timestamp: number;
}

interface CatalogCandidate {
  promptId: string;
  category: string;
  state: string;
  twiText: string;
  englishText: string;
  audioUrl: string;
}

// ── In-Memory Cache for Audio Match Results ─────────────────────────────────
const audioMatchCache = new Map<string, GeminiAudioMatchResult>();
const MAX_CACHE_ENTRIES = 500;

export function getCachedAudioMatch(replyText: string, language: string): GeminiAudioMatchResult | null {
  const normKey = `${language}:${(replyText || "").trim().toLowerCase()}`;
  return audioMatchCache.get(normKey) || null;
}

export function setCachedAudioMatch(replyText: string, language: string, result: GeminiAudioMatchResult): void {
  const normKey = `${language}:${(replyText || "").trim().toLowerCase()}`;
  if (audioMatchCache.size >= MAX_CACHE_ENTRIES) {
    const oldestKey = audioMatchCache.keys().next().value;
    if (oldestKey) audioMatchCache.delete(oldestKey);
  }
  audioMatchCache.set(normKey, result);
}

export function clearAudioMatchCache(): void {
  audioMatchCache.clear();
}

// ── In-Memory Store for Gemini Conversational Replies ───────────────────────
const storedGeminiReplies = new Map<string, StoredGeminiReply>();
const MAX_STORED_REPLIES = 200;

/**
 * Stores a conversational reply generated by Gemini in memory so the Audio Matcher
 * can verify that the reply originated from the conversation flow.
 */
export function storeGeminiConversationReply(
  text: string,
  language: string = "twi",
  sessionId?: string
): void {
  if (!text || typeof text !== "string") return;
  const trimmed = text.trim();
  if (!trimmed) return;

  const key = `${sessionId || "global"}:${trimmed.toLowerCase()}`;
  const record: StoredGeminiReply = {
    text: trimmed,
    language,
    sessionId,
    timestamp: Date.now(),
  };

  storedGeminiReplies.set(key, record);
  storedGeminiReplies.set(`text:${trimmed.toLowerCase()}`, record);

  if (storedGeminiReplies.size > MAX_STORED_REPLIES) {
    const oldestKey = storedGeminiReplies.keys().next().value;
    if (oldestKey) storedGeminiReplies.delete(oldestKey);
  }
}

export function isGeminiConversationReply(text: string, sessionId?: string): boolean {
  if (!text) return false;
  const trimmed = text.trim().toLowerCase();
  if (sessionId && storedGeminiReplies.has(`${sessionId}:${trimmed}`)) return true;
  return storedGeminiReplies.has(`text:${trimmed}`);
}

export function getStoredGeminiReply(text: string, sessionId?: string): StoredGeminiReply | null {
  if (!text) return null;
  const trimmed = text.trim().toLowerCase();
  if (sessionId && storedGeminiReplies.has(`${sessionId}:${trimmed}`)) {
    return storedGeminiReplies.get(`${sessionId}:${trimmed}`) || null;
  }
  return storedGeminiReplies.get(`text:${trimmed}`) || null;
}

// Build pre-indexed candidate catalog of available recorded audio clips
function buildCandidateCatalog(): CatalogCandidate[] {
  const candidates: CatalogCandidate[] = [];
  const seenIds = new Set<string>();

  // 1. From TWI_SEQUENTIAL_FLOW_STEPS
  for (const step of TWI_SEQUENTIAL_FLOW_STEPS) {
    if (step.audioUrl && step.id) {
      candidates.push({
        promptId: step.id,
        category: step.name,
        state: step.id,
        twiText: step.spokenTextTwi,
        englishText: step.spokenTextEn,
        audioUrl: step.audioUrl,
      });
      seenIds.add(step.id);
    }
  }

  // 2. From prompts.json linked with AUDIO_RECORDINGS
  const manifestPrompts = (promptManifest as any).prompts || [];
  for (const p of manifestPrompts) {
    if (seenIds.has(p.id)) continue;
    const twiAudio = p.audio?.twi;
    if (!twiAudio) continue;

    const rec = AUDIO_RECORDINGS.find((r) => r.promptId === p.id && r.url);
    const audioUrl = rec?.url || `/audio/supplied/${twiAudio.replace(/^audio\/Twi\//, "Twi/")}`;

    candidates.push({
      promptId: p.id,
      category: p.category,
      state: p.state,
      twiText: p.twi || "",
      englishText: p.english || "",
      audioUrl,
    });
    seenIds.add(p.id);
  }

  // 3. From remaining AUDIO_RECORDINGS with spokenText
  for (const rec of AUDIO_RECORDINGS) {
    if (rec.promptId && !seenIds.has(rec.promptId) && rec.url && rec.spokenText) {
      candidates.push({
        promptId: rec.promptId,
        category: rec.category,
        state: rec.state || rec.promptId,
        twiText: rec.language === "twi" ? rec.spokenText : "",
        englishText: rec.language === "en" ? rec.spokenText : "",
        audioUrl: rec.url,
      });
      seenIds.add(rec.promptId);
    }
  }

  return candidates;
}

const CATALOG_CANDIDATES = buildCandidateCatalog();

/**
 * Fast detection of dynamic transaction parameters that can never match a static studio audio clip.
 */
function containsDynamicTransactionData(text: string): boolean {
  const lower = text.toLowerCase();
  // Amounts, fee mentions, reference numbers, or 10-digit Ghanaian mobile numbers
  if (/\b(?:ghs|cedis?|pesewas?)\s*\d+/i.test(lower)) return true;
  if (/\d+\s*(?:ghs|cedis?)/i.test(lower)) return true;
  if (/\b\d{1,4}(?:\.\d{1,2})?\s*(?:ghs|cedis)/i.test(lower)) return true;
  if (/\b(?:024|054|055|059|020|050|027|057|026|056)\d{7}\b/.test(lower)) return true;
  if (/\b(?:ref|reference|txid|transaction id|kɔdo)\b/i.test(lower) && /\d{4,}/.test(lower)) return true;
  return false;
}

/**
 * Matches an AI reply to the Audio Link Catalog using:
 * 1. In-memory cache (0 tokens, < 1ms)
 * 2. Local-first deterministic & catalog matching (0 tokens, < 2ms)
 * 3. Gemini LLM matching ONLY when the reply originated from the Gemini conversation flow
 *    and local matcher is uncertain (< 0.80 confidence).
 */
export async function matchAiReplyWithGemini(
  replyText: string,
  language: "twi" | "en" = "twi",
  literacyOptions?: CallerLiteracyOptions
): Promise<GeminiAudioMatchResult> {
  const cleanReply = (replyText || "").trim();
  if (!cleanReply) {
    return {
      matchFound: false,
      requiresTts: true,
      reason: "Empty reply text provided.",
    };
  }

  const isTwi = language.startsWith("tw") || language === "twi";
  const langKey = isTwi ? "twi" : "en";

  // ── Step 1: In-Memory Cache Lookup (0 tokens) ─────────────────────────────
  const cached = getCachedAudioMatch(cleanReply, langKey);
  if (cached) {
    return {
      ...cached,
      reason: `${cached.reason} (in-memory cache hit)`,
    };
  }

  // ── Step 2: Dynamic Content Exclusion (0 tokens) ──────────────────────────
  if (containsDynamicTransactionData(cleanReply)) {
    const dynamicResult: GeminiAudioMatchResult = {
      matchFound: false,
      requiresTts: true,
      reason: "Contains dynamic transaction details (amounts, fees, or phone); requires dynamic TTS synthesis.",
      confidence: 0.99,
    };
    setCachedAudioMatch(cleanReply, langKey, dynamicResult);
    return dynamicResult;
  }

  // ── Step 3: Local-First Audio Matching (0 tokens) ─────────────────────────
  const localMatch = matchReplyToAudio(cleanReply, langKey, { minConfidence: 0.80 });
  if (localMatch.match && localMatch.confidence >= 0.80 && localMatch.audioUrl) {
    const localResult: GeminiAudioMatchResult = {
      matchFound: true,
      promptId: localMatch.recording?.promptId || (localMatch.flowStep as any)?.stepId || localMatch.flowStep?.id,
      audioUrl: localMatch.audioUrl,
      title: localMatch.title || "Matched Studio Prompt",
      spokenText: localMatch.spokenText,
      reason: `Local-first catalog match (${localMatch.matchReason || "high confidence"})`,
      requiresTts: false,
      confidence: localMatch.confidence,
    };
    setCachedAudioMatch(cleanReply, langKey, localResult);
    return localResult;
  }

  // Fast check: exact semantic catalog match
  const fallbackMatch = semanticCatalogFallback(cleanReply, isTwi);
  if (fallbackMatch.matchFound && (fallbackMatch.confidence ?? 0) >= 0.85) {
    setCachedAudioMatch(cleanReply, langKey, fallbackMatch);
    return fallbackMatch;
  }

  // ── Step 4: Gated Gemini Call ─────────────────────────────────────────────
  // Gemini is ONLY called when the reply originated from the conversation flow
  const isFromConversationFlow =
    literacyOptions?.isGeminiConversation === true ||
    isGeminiConversationReply(cleanReply, literacyOptions?.sessionId);

  // If NOT from conversation flow, do NOT burn Gemini tokens. Fall back directly to local resolution.
  if (!isFromConversationFlow) {
    const nonGeminiResult: GeminiAudioMatchResult = {
      matchFound: false,
      requiresTts: true,
      reason: "Routine non-conversational prompt; resolved locally without LLM tokens.",
      confidence: 0.85,
    };
    setCachedAudioMatch(cleanReply, langKey, nonGeminiResult);
    return nonGeminiResult;
  }

  // Retrieve stored reply from memory to confirm state
  const stored = getStoredGeminiReply(cleanReply, literacyOptions?.sessionId);
  const textToSend = stored?.text || cleanReply;

  // Local matcher was uncertain on a genuine Gemini conversational reply.
  // Send stored reply together with the prompt file catalog candidates.
  const literacyLevel = literacyOptions?.literacyLevel || "standard";

  const candidatesSummary = CATALOG_CANDIDATES.map((c) => ({
    id: c.promptId,
    category: c.category,
    twi: c.twiText,
    en: c.englishText,
    url: c.audioUrl,
  }));

  const systemInstruction = `You are the Audio Dispatch & Literacy Intelligence Engine for Ɔkwankyerɛfo Pa, an accessible Ghanaian Akan (Twi) and English Voice Mobile Money (MoMo) IVR platform.
Your job is to examine an AI-generated assistant reply and decide whether it matches an authentic pre-recorded human studio audio clip, or whether it requires dynamic Text-to-Speech (TTS) synthesis.

LITERACY & ACCESSIBILITY GUIDELINES:
- Many callers have limited formal textual literacy or are elderly. They rely on simple, colloquial, warm, spoken Akan expressions.
- If the AI reply conveys the same core intent and action as a pre-recorded studio audio clip, prefer the pre-recorded authentic human recording.
- DYNAMIC CONTENT EXCLUSION: If the AI reply contains specific dynamic values (amounts, recipient names, fees, custom status), static audio cannot be used. Mark matchFound=false and requiresTts=true.
- If none of the audio clips match, mark matchFound=false and requiresTts=true.

Return ONLY a valid JSON object with:
{
  "matchFound": boolean,
  "matchedPromptId": string | null,
  "audioUrl": string | null,
  "reason": string,
  "requiresTts": boolean,
  "literacyNote": string
}`;

  const promptContent = `Language: ${isTwi ? "Akan Twi" : "English"}
Caller Literacy Profile: ${literacyLevel} (prefers intuitive, colloquial spoken clarity)
AI Reply Text to play (stored from conversation): "${textToSend}"

Prompt Catalog Candidates (from prompts.json manifest):
${JSON.stringify(candidatesSummary.slice(0, 30), null, 2)}

Determine if an authentic studio audio clip matches this reply, or if dynamic TTS is required.`;

  try {
    const client = UnifiedGeminiClient.getInstance("telephony");
    if (client.isAvailable()) {
      const resultText = await client.executeWithTimeout(
        "gemini-audio-link-matcher",
        async (ai) => {
          const response = await ai.models.generateContent({
            model: "gemini-3.8-flash",
            contents: [
              { role: "user", parts: [{ text: systemInstruction + "\n\n" + promptContent }] },
            ],
            config: {
              temperature: 0.1,
              responseMimeType: "application/json",
            },
          });
          return response.text || "";
        },
        4000,
        1,
        undefined,
        3500,
        "gemini-3.8-flash"
      );

      if (resultText) {
        const parsed = JSON.parse(resultText);
        if (parsed.matchFound && parsed.matchedPromptId) {
          const found = CATALOG_CANDIDATES.find(
            (c) => c.promptId.toLowerCase() === String(parsed.matchedPromptId).toLowerCase()
          );
          const resolvedUrl = found?.audioUrl || parsed.audioUrl;
          if (resolvedUrl) {
            const successMatch: GeminiAudioMatchResult = {
              matchFound: true,
              promptId: found?.promptId || parsed.matchedPromptId,
              audioUrl: resolvedUrl,
              title: found?.category || "Matched Studio Prompt",
              spokenText: isTwi ? found?.twiText : found?.englishText,
              reason: parsed.reason || "Semantic and literacy match via Gemini",
              requiresTts: false,
              literacyContext: parsed.literacyNote,
              confidence: 0.95,
            };
            setCachedAudioMatch(cleanReply, langKey, successMatch);
            return successMatch;
          }
        }

        const ttsResult: GeminiAudioMatchResult = {
          matchFound: false,
          requiresTts: true,
          reason: parsed.reason || "Dynamic or non-catalog content; requires TTS synthesis.",
          literacyContext: parsed.literacyNote,
          confidence: 0.90,
        };
        setCachedAudioMatch(cleanReply, langKey, ttsResult);
        return ttsResult;
      }
    }
  } catch (err: any) {
    console.warn("[GeminiAudioMatcher] Gemini evaluation notice, using heuristic fallback:", err?.message);
  }

  // Graceful Semantic Fallback when offline or rate-limited
  const finalFallback = semanticCatalogFallback(cleanReply, isTwi);
  setCachedAudioMatch(cleanReply, langKey, finalFallback);
  return finalFallback;
}

/**
 * Deterministic semantic fallback matching when Gemini is offline or rate-limited
 */
function semanticCatalogFallback(cleanReply: string, isTwi: boolean): GeminiAudioMatchResult {
  const lower = cleanReply.toLowerCase();

  for (const candidate of CATALOG_CANDIDATES) {
    const target = (isTwi ? candidate.twiText : candidate.englishText).toLowerCase();
    if (!target) continue;

    // High semantic similarity
    if (lower === target || (lower.length > 15 && target.includes(lower)) || (target.length > 15 && lower.includes(target))) {
      return {
        matchFound: true,
        promptId: candidate.promptId,
        audioUrl: candidate.audioUrl,
        title: candidate.category,
        spokenText: isTwi ? candidate.twiText : candidate.englishText,
        reason: "Exact/high semantic match to catalog recording",
        requiresTts: false,
        confidence: 0.92,
      };
    }
  }

  return {
    matchFound: false,
    requiresTts: true,
    reason: "No pre-recorded studio audio matches; fallback to TTS synthesis.",
    confidence: 0.70,
  };
}
